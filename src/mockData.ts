export function getStudentStatus(student: Student): 'Cleared' | 'Partial' | 'Overdue' {
  if (student.totalPaid >= student.termTuitionFee) return 'Cleared';
  if (student.totalPaid === 0) return 'Overdue';
  return 'Partial';
}

export function getStudentBalance(student: Student): number {
  return Math.max(0, student.termTuitionFee - student.totalPaid);
}

export function formatKSh(amount: number): string {
  return 'KSh ' + amount.toLocaleString('en-KE');
}
